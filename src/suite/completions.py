from __future__ import annotations

import os
import re
import shlex
import shutil
import subprocess
import tempfile
from collections.abc import Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import click
from click import types as click_types

from .errors import SuiteError


@dataclass
class _OptionSpec:
    key: str
    opts: tuple[str, ...]
    takes_value: bool
    nargs: int
    param_type: click.ParamType[Any]


@dataclass
class _ArgumentSpec:
    param_type: click.ParamType[Any]
    nargs: int


@dataclass
class _CommandSpec:
    function: str
    name: str
    options: list[_OptionSpec] = field(default_factory=list)
    arguments: list[_ArgumentSpec] = field(default_factory=list)
    children: list[_CommandSpec] = field(default_factory=list)


@dataclass
class _Generator:
    prog_name: str
    next_id: int = 1

    @property
    def root_function(self) -> str:
        return f"_{_sanitize(self.prog_name)}_complete"

    def _build(
        self,
        command: click.Command,
        name: str,
        *,
        root: bool = False,
    ) -> _CommandSpec:
        if root:
            function = self.root_function
        else:
            function = f"_{_sanitize(self.prog_name)}_cmd_{self.next_id}"
            self.next_id += 1

        spec = _CommandSpec(function=function, name=name)
        context = click.Context(command, info_name=name)
        settings = command.context_settings or {}
        context.help_option_names = list(
            settings.get("help_option_names", ["--help"])
        )

        options: list[click.Option] = [
            param
            for param in command.params
            if isinstance(param, click.Option) and not param.hidden
        ]
        help_option = command.get_help_option(context)
        if help_option is not None and not help_option.hidden:
            options.append(help_option)

        for index, option in enumerate(options):
            takes_value = not option.is_flag and not option.count
            spec.options.append(
                _OptionSpec(
                    key=str(index),
                    opts=tuple(option.opts + option.secondary_opts),
                    takes_value=takes_value,
                    nargs=max(1, option.nargs) if takes_value else 0,
                    param_type=option.type,
                )
            )

        for param in command.params:
            if isinstance(param, click.Argument):
                spec.arguments.append(
                    _ArgumentSpec(
                        param_type=param.type,
                        nargs=param.nargs,
                    )
                )

        if isinstance(command, click.Group):
            for child_name in command.list_commands(context):
                child = command.get_command(context, child_name)
                if child is None or child.hidden:
                    continue
                spec.children.append(self._build(child, child_name))
        return spec


def generate_bash(group: click.Command, prog_name: str, version: str) -> str:
    """Return the complete bash completion script."""
    generator = _Generator(prog_name=prog_name)
    spec = generator._build(group, prog_name, root=True)
    lines = [
        f"# bash completion for {prog_name} {version}",
        f"# Generated by `{prog_name} --completions`; "
        "do not edit. This file is overwritten.",
        "",
        _prefix_function(prog_name),
        "",
    ]
    for command in _walk(spec):
        lines.extend(_render_function(command, prog_name))
        lines.append("")
    lines.append(
        f"complete -o nosort -o bashdefault -o default "
        f"-F {spec.function} {shlex.quote(prog_name)}"
    )
    return "\n".join(lines) + "\n"


def _prefix_function(prog_name: str) -> str:
    return f"""\
_{_sanitize(prog_name)}_prefix_results() {{
    local _prefix=$1
    local _i
    for (( _i = 0; _i < ${{#COMPREPLY[@]}}; _i++ )); do
        COMPREPLY[_i]="${{_prefix}}=${{COMPREPLY[_i]}}"
    done
}}"""


def completion_path(prog: str = "suite") -> Path:
    """Return the bash completion script path for ``prog``."""
    base = _completion_base()
    return base / "bash-completion" / "completions" / f"{prog}.bash"


def has_bash_completion(prog: str = "suite") -> bool:
    """Return True when ``prog``'s bash completion script is installed."""
    return completion_path(prog).is_file()


def install_bash_completion(
    group: click.Command, prog_name: str, version: str
) -> Path:
    """Write the script, print its path, and return the path."""
    path = completion_path(prog_name)
    script = generate_bash(group, prog_name, version)
    warning = _bash_warning()
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        descriptor, name = tempfile.mkstemp(
            dir=path.parent,
            prefix=f".{path.name}.",
            text=True,
        )
        try:
            if hasattr(os, "fchmod"):
                os.fchmod(descriptor, 0o644)
            with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
                handle.write(script)
            Path(name).replace(path)
        except BaseException:
            Path(name).unlink(missing_ok=True)
            raise
    except OSError as exc:
        raise SuiteError(
            f"could not write completion script {path}: {exc}"
        ) from exc

    absolute = path.expanduser().absolute()
    click.echo(absolute)
    click.echo(f"To use it in this shell:\n  source {absolute}", err=True)
    if warning is not None:
        click.echo(f"warning: {warning}", err=True)
    return path


def _completion_base() -> Path:
    user_dir = os.environ.get("BASH_COMPLETION_USER_DIR", "")
    for entry in user_dir.split(os.pathsep):
        if entry.strip():
            return Path(entry).expanduser().absolute()
    data_home = os.environ.get("XDG_DATA_HOME", "")
    if data_home.strip():
        return Path(data_home).expanduser().absolute()
    return (Path.home() / ".local" / "share").expanduser().absolute()


def _bash_warning() -> str | None:
    bash = shutil.which("bash")
    if bash is None:
        return (
            "bash was not found; the completion script still works "
            "when sourced from bash >= 4.4."
        )
    try:
        result = subprocess.run(
            [
                bash,
                "-c",
                'printf "%s.%s" "${BASH_VERSINFO[0]}" "${BASH_VERSINFO[1]}"',
            ],
            check=False,
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.SubprocessError):
        return (
            "could not determine the bash version; the completion "
            "script requires bash >= 4.4."
        )
    found = result.stdout.strip()
    try:
        major_text, minor_text = found.split(".", 1)
        major, minor = int(major_text), int(minor_text)
    except ValueError:
        return (
            f"could not parse the bash version {found!r}; the "
            "completion script requires bash >= 4.4."
        )
    if (major, minor) < (4, 4):
        return (
            f"bash {found} is older than 4.4; install a newer bash "
            "to use this completion script."
        )
    return None


def _walk(spec: _CommandSpec) -> list[_CommandSpec]:
    result = [spec]
    for child in spec.children:
        result.extend(_walk(child))
    return result


def _render_function(spec: _CommandSpec, prog_name: str) -> list[str]:
    lines = [f"{spec.function}() {{"]
    lines.append("    local start=${1:-1}")
    lines.append("    local cur=${COMP_WORDS[COMP_CWORD]}")
    lines.append("    local i word _opt _child _choice")
    lines.append("    local positionals=0")
    lines.append("    local no_opts=0")
    lines.append("    local _suite_pending=''")
    lines.append("    local _suite_pending_index=0")
    lines.append("    local _need=0")

    opts = sorted({opt for option in spec.options for opt in option.opts})
    lines.append(
        "    local -a _opts=("
        + " ".join(shlex.quote(opt) for opt in opts)
        + ")"
    )
    if spec.children:
        lines.append(
            "    local -a _children=("
            + " ".join(shlex.quote(child.name) for child in spec.children)
            + ")"
        )
    lines.append("")
    lines.append("    for (( i = start; i < COMP_CWORD; i++ )); do")
    lines.append("        word=${COMP_WORDS[i]}")
    lines.append("        if (( no_opts == 0 )); then")
    lines.append("            if [[ $word == '--' ]]; then")
    lines.append("                no_opts=1")
    lines.append("                continue")
    lines.append("            fi")
    lines.append('            case "$word" in')

    value_options = [option for option in spec.options if option.takes_value]
    for option in value_options:
        patterns = "|".join(shlex.quote(opt) for opt in option.opts)
        lines.append(f"                {patterns})")
        lines.append(f"                    _need={option.nargs}")
        lines.append(
            "                    while (( _need > 0 "
            "&& i + 1 < COMP_CWORD )); do"
        )
        lines.append("                        i=$((i + 1))")
        lines.append("                        _need=$((_need - 1))")
        lines.append("                    done")
        lines.append("                    if (( _need > 0 )); then")
        lines.append(
            f"                        _suite_pending={shlex.quote(option.key)}"
        )
        lines.append(
            "                        _suite_pending_index="
            f"$(({option.nargs} - _need))"
        )
        lines.append("                    fi")
        lines.append("                    continue")
        lines.append("                    ;;")
    lines.append("            esac")
    lines.append("            if [[ $word == -* ]]; then")
    lines.append("                continue")
    lines.append("            fi")
    lines.append("        fi")

    if spec.children:
        lines.append("        if (( no_opts == 0 && positionals == 0 )); then")
        lines.append('            case "$word" in')
        for child in spec.children:
            lines.append(
                f"                {shlex.quote(child.name)}) "
                f"{child.function} $((i + 1)); return 0 ;;"
            )
        lines.append("            esac")
        lines.append("        fi")
    lines.append("        positionals=$((positionals + 1))")
    lines.append("    done")
    lines.append("")

    lines.extend(_render_equals_completion(value_options, prog_name))
    lines.append("")
    lines.append("    if (( no_opts == 0 )); then")
    lines.append("        if [[ $cur == -* ]]; then")
    lines.append('            for _opt in "${_opts[@]}"; do')
    lines.append(
        '                [[ $_opt == "$cur"* ]] && COMPREPLY+=( "$_opt" )'
    )
    lines.append("            done")
    lines.append("            return 0")
    lines.append("        fi")
    lines.append("    fi")
    lines.append("")
    lines.extend(_render_pending_completion(value_options))
    lines.append("")

    lines.extend(_render_positionals(spec.arguments))
    if spec.children:
        lines.append("    if (( no_opts == 0 && positionals == 0 )); then")
        lines.append('        for _child in "${_children[@]}"; do')
        lines.append(
            '            [[ $_child == "$cur"* ]] && COMPREPLY+=( "$_child" )'
        )
        lines.append("        done")
        lines.append("    fi")
    if spec.options:
        lines.append("    if (( no_opts == 0 )); then")
        lines.append('        for _opt in "${_opts[@]}"; do')
        lines.append(
            '            [[ $_opt == "$cur"* ]] && COMPREPLY+=( "$_opt" )'
        )
        lines.append("        done")
        lines.append("    fi")
    lines.append("    return 0")
    lines.append("}")
    return lines


def _render_equals_completion(
    options: Sequence[_OptionSpec],
    prog_name: str,
) -> list[str]:
    lines = [
        "    if [[ $no_opts -eq 0 && $cur == --*=* ]]; then",
        "        _opt=${cur%%=*}",
        "        cur=${cur#*=}",
        '        case "$_opt" in',
    ]
    for option in options:
        patterns = "|".join(
            shlex.quote(opt) for opt in option.opts if opt.startswith("-")
        )
        if not patterns:
            continue
        lines.append(f"            {patterns})")
        param_type = _narrow(option.param_type, 0)
        lines.extend(_value_lines(param_type, "                "))
        lines.append(
            f'                _{_sanitize(prog_name)}_prefix_results "$_opt"'
        )
        lines.append("                compopt -o nospace 2>/dev/null || true")
        lines.append("                return 0")
        lines.append("                ;;")
    lines.append("        esac")
    lines.append("        cur=${COMP_WORDS[COMP_CWORD]}")
    lines.append("    fi")
    return lines


def _render_pending_completion(
    options: Sequence[_OptionSpec],
) -> list[str]:
    lines = [
        "    if [[ -n $_suite_pending ]]; then",
        '        case "$_suite_pending:$_suite_pending_index" in',
    ]
    for option in options:
        key = shlex.quote(option.key)
        if isinstance(option.param_type, click.Tuple):
            for index in range(option.nargs):
                lines.append(f"            {key}:{index})")
                lines.extend(
                    _value_lines(
                        _narrow(option.param_type, index),
                        "                ",
                    )
                )
                lines.append("                ;;")
        else:
            lines.append(f"            {key}:*)")
            lines.extend(_value_lines(option.param_type, "                "))
            lines.append("                ;;")
    lines.append("        esac")
    lines.append("        return 0")
    lines.append("    fi")
    return lines


def _render_positionals(
    arguments: Sequence[_ArgumentSpec],
) -> list[str]:
    if not arguments:
        return []
    lines = ["    case $positionals in"]
    start = 0
    for argument in arguments:
        if argument.nargs == -1:
            pattern = "*"
        else:
            pattern = "|".join(
                str(index) for index in range(start, start + argument.nargs)
            )
        lines.append(f"        {pattern})")
        if isinstance(argument.param_type, click.Tuple):
            lines.append(f"            case $((positionals - {start})) in")
            for index, param_type in enumerate(argument.param_type.types):
                lines.append(f"                {index})")
                lines.extend(_value_lines(param_type, "                    "))
                lines.append("                    ;;")
            if argument.param_type.types:
                lines.append("                *)")
                lines.extend(
                    _value_lines(
                        argument.param_type.types[-1],
                        "                    ",
                    )
                )
                lines.append("                    ;;")
            lines.append("            esac")
        else:
            lines.extend(_value_lines(argument.param_type, "            "))
        lines.append("            ;;")
        if argument.nargs != -1:
            start += argument.nargs
    lines.append("    esac")
    return lines


def _value_lines(param_type: click.ParamType[Any], indent: str) -> list[str]:
    if isinstance(param_type, click.Choice):
        choices = " ".join(
            shlex.quote(str(choice)) for choice in param_type.choices
        )
        return [
            f"{indent}local -a _choices=({choices})",
            f"{indent}local _choice",
            f'{indent}for _choice in "${{_choices[@]}}"; do',
            f'{indent}    [[ $_choice == "$cur"* ]] '
            '&& COMPREPLY+=( "$_choice" )',
            f"{indent}done",
        ]
    if isinstance(param_type, click.Path):
        if param_type.file_okay is False:
            return _directory_lines(indent)
        return _file_lines(indent)
    if isinstance(param_type, click.File):
        return _file_lines(indent)
    if isinstance(
        param_type,
        (
            click_types.IntParamType,
            click_types.FloatParamType,
            click_types.BoolParamType,
        ),
    ):
        return []
    return []


def _file_lines(indent: str) -> list[str]:
    return [
        f"{indent}if declare -F _filedir >/dev/null; then",
        f"{indent}    _filedir",
        f"{indent}else",
        f'{indent}    COMPREPLY=( $(compgen -f -- "$cur") )',
        f"{indent}fi",
    ]


def _directory_lines(indent: str) -> list[str]:
    return [
        f"{indent}if declare -F _filedir >/dev/null; then",
        f"{indent}    _filedir -d",
        f"{indent}else",
        f'{indent}    COMPREPLY=( $(compgen -d -- "$cur") )',
        f"{indent}fi",
    ]


def _narrow(
    param_type: click.ParamType[Any], index: int
) -> click.ParamType[Any]:
    if isinstance(param_type, click.Tuple) and param_type.types:
        return param_type.types[min(index, len(param_type.types) - 1)]
    return param_type


def _sanitize(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name)
